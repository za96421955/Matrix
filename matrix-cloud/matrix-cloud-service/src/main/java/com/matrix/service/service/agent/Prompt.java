package com.matrix.service.service.agent;

import com.matrix.common.util.JSONSchemaUtil;
import com.matrix.service.service.agent.schema.TaskChain;

/**
 * 智能体提示词
 * <p> <功能详细描述> </p>
 *
 * @author 陈晨
 */
public interface Prompt {

    String MEMORY_MANAGER = """
            ## 当前记忆
            ```
            %s
            ```
            
            ## 修改要求
            ```
            %s
            ```
            
            ## 整理后的示例（仅供参考）
            ```
            ## 短期记忆
            - [yyyy-MM-dd] 正在准备下周一的产品评审会议
            - [2026-07-15] 最近在调研向量数据库
            - [2026-07-17] ...
            
            ## 长期记忆
            - 职业：后端开发，5 年 Java 经验
            - 饮食：素食，不吃辣
            - 工作时长：偏好深度工作，上午编码效率最高
            
            ## 谏言
            - 用户喜欢结构化输出，给信息时优先用列表或分点
            - 用户在讨论技术方案时，更关注性能指标而非代码细节
            ```
            
            按要求修改<当前记忆>，输出修改后的记忆内容（仅输出合并结果，不要其他说明）：
            """;

    /** 公共 */
    interface Common {

        /** 操作终端 */
        String OPERATION_CLIENT_ID = "操作终端: %s\n\n";

        /** 工作目录 */
        String WORKING_DIRECTORY = "工作目录：%s\n\n";

        /** 规划 */
        String PLAN = """
            1. 帮助用户规划任务，输出<任务列表>
            2. 任何疑问立即向用户提出，一步一步地完善细节信息

            ## 约束
            - 优先使用 less、grep、cat，少用 find
            - 输出时，对执行过程和结果进行完整总结，不要使用任何 emoji 表情
            - 除非用户的需求已经非常明确且数据完整，否则你仅负责帮助用户规划并输出任务列表、禁止执行任何写操作
            
            ## 任务列表格式
            ```markdown
            ## 任务列表
            - [X] {已完成的任务描述}
            - [ ] {待执行的任务描述}
            
            ## 约束
            - {执行操作时的约束条件}
            - {执行操作时的约束条件}
            
            ## 工作流程
            - 若未明确说明，默认按任务列表依次执行
            ```
            """;

        /** 环节 */
        String GET_PATTERN_NO = WORKING_DIRECTORY + """
            根据上下文、需求是否清晰、任务规划是否完善等信息，判断当前任务应该进入以下哪个环节，还是继续当前环节：
            ```
            %s
            ```
            
            ## 当前环节：%s
            
            ## 约束
            - 仅输出环节编号，禁止执行任何写操作
            """;

        /** 需求分析 */
        String DEMAND_ANALYZE = WORKING_DIRECTORY + """
            1. 理解分析用户需求，帮助用户梳理需求内容，对齐、完善需求细节
            2. 任何疑问立即向用户提出，必要时可向用户要求补充相关信息
            3. 禁止执行任何写操作
            4. 当需求已经完全明确无遗漏、无问题时，对需求进行总结输出完整的SDD，并在结尾输出 "%s"
            
            ## 约束
            - 优先使用 less、grep、cat，少用 find
            - 不要使用任何 emoji 表情
            """;

    }

    /** 任务链 */
    interface Task {

        String GENERATE_TASK = """
            1. 首先分析、理解用户需求，利用工具收集、完善相关信息
            2. 然后拆解、规划任务链，要求目标明确、前后衔接可闭环，关键步骤需设置检查项
            3. 最后按<输出格式>输出<任务列表>，不执行任何写操作
            
            ## 约束
            1. 不输出任何解释、思考等说明性内容，直接输出任务列表
            2. 不使用任何 emoji 表情
            
            ## 输出格式
            ```json
            %s
            ```
            """.formatted(JSONSchemaUtil.generate(TaskChain.class));

        String CHECK_TASK_LIST = """
            1. 检查任务流程是否健康、是否存在死循环、冗余步骤等会导致资源浪费、重复执行的情况
            2. 健康: true; 不健康: 说明原因及修改建议
            3. 仅输出 true/问题原因, 不要任何解释
            """;

        String EXECUTOR_TASK = """
            ## 工作目录
            %s
            
            ---
            你是任务执行链中的一个执行单元。
            【当前任务】%s，是整体规划中的一个步骤。
            【上下文】中已包含之前所有步骤的完整执行结果，你可以完全信任这些结果。

            要求：
            1. **严格仅执行当前这一个步骤**，不要重复执行之前已完成的操作，直接基于已有上下文继续。
            2. 如果当前步骤的前置条件在上下文中已满足，则直接跳过前置检查，进入核心逻辑。
            3. 对执行过程和结果进行完整总结，不要使用 emoji。
            
            ---
            ## 执行方案：
            %s
            
            ## 任务目标：
            %s
            
            ## 关键结果:
            %s
            """;

        String CHECK_TASK_RESULT = """
            1. 理解上下文, 判断任务结果是否满足用户需求
            2. 满足: true; 不满足: 说明原因
            3. 仅输出 true/问题原因, 不要任何解释
            """;

        String SUMMARY_RESULT = """
            1. 分析任务完成情况
            2. 如果是<研发>任务，则补充 git diff 差异信息
            3. 对执行过程和结果进行完整总结，不要使用任何 emoji 表情
            """;
    }

    /** 观察者 */
    interface Observer {
        String CHECK_RESULT = """
            1. 观察任务执行结果是否满足目标
            2. 满足: true; 不满足: 说明原因
            3. 仅输出 true/问题原因, 不要任何解释
            
            ## 任务目标：
            %s
            """;

        String CHECK_TASK = """
            1. 任务执行结果不满足目标，根据原因判断是否需要重新规划任务
            2. 不需要: false; 需要: 说明原因
            3. 仅输出 false/说明原因, 不要任何解释
            
            ## 任务目标：
            %s
            """;
    }

    /** 需求开发 */
    interface Coding {

        String PLAN_DEVELOP = Common.WORKING_DIRECTORY + Common.PLAN + """
            
            ## 重点
            - 帮助用户梳理、编排<研发>任务
            - <研发>完后后，项目必须编译通过
            - 当任务列表已经完全明确、没有任何疑问及需要用户补充的信息后，在结尾输出 "%s"
            """;

    }

    /** 资料整理 */
    interface Information {

        String DEMAND_ANALYZE = Common.DEMAND_ANALYZE + """
            
            ## 重点
            你必须向用户了解清楚以下事项：
            1. 背景与用途
            例 (仅供参考):
            - 汇报 PPT: 需要按逻辑故事线分组，提炼核心观点文件
            - 课题研究: 需要按主题/文献/数据/图表分类，方便引用
            - 个人知识库: 需要统一命名、去重、打标签、建立索引
            2. 操作规则
            例 (仅供参考):
            - 重新归类到不同文件夹
            - 统一重命名 (例如: 日期-主题-版本)
            - 提取摘要并生成目录或索引
            - 删除重复、过期文件
            - 以上全部
            3. 输出物 (仅限文本)
            例 (仅供参考):
            - Markdown
            - HTML
            """;

        String PLAN_OPERATION = Common.WORKING_DIRECTORY + Common.PLAN + """
            
            ## 重点
            - 帮助用户梳理、编排<资料整理>任务
            - 禁止擅自删除任何文件, 文件编辑前必须备份
            - 当任务列表已经完全明确、没有任何疑问及需要用户补充的信息后，在结尾输出 "%s"
            """;

        String OUTPUT_HTML = Common.WORKING_DIRECTORY + """
            
            1. 不论用户要求的输出物是什么, 都额外输出一份 HTML 文件（单文件）
            2. 根据资料特性、类别等要素，选择最适合用户身份的 HTML 主题、配色、动画效果 等元素
            3. 如果用户对输出物有汇报、授课、路演等与他人表述的需求，则输出的 HTML 内容需要分页处理，方便导出为图片、PDF等文件
            4. 将 HTML 的文本与其他元素分开，每一页右上角都必须有"编辑"按钮，点击编辑后，用户可以自行调整页面的文本内容
            5. 完成后, 打开 HTML
            """;

    }

}
