    /** SMART 目标设定 */
    interface SMART {

        String CHECK_NEED = """
            1. 查看上下文，快速判断用户需求/任务是否需要 SMART 分析。
            2. 需要: true, 不需要: false
            
            ## 示例
            user: 给 demo.js 添加 hello world
            assistant: false
            
            输出 (不要任何解释):
            """;

        String CONFIRM = """
            1. 围绕<SMART原则>与用户沟通，协助用户制定明确的任务目标
            2. 当信息充足，S、M、A、R、T都具备后，按格式输出目标信息

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 你仅负责协助用户制定任务目标，禁止执行任何写操作
            
            ## SMART原则
            1. 核心目标，清晰界定'要完成什么'。
            2. 验收标准，包含数字/比率/交付物等量化指标。
            3. 资源与约束条件，执行时不能跨越的界。必须和用户确认。
            4. 背景与意图，明确任务方向。必须和用户确认。
            5. 截止日期，格式：yyyy-MM-dd HH:mm:ss。必须用户给出。
            
            ## 输出格式
            ```json
            %s
            ```
            """;

        String CONFIRM_CHECK = """
            1. 检查任务目标是否还有疑问或需要用户补充的信息
            2. 没疑问: PASS; 有疑问: TODO
            3. 仅输出 PASS/TODO, 不要任何解释
            """;

    }

    /** 思维链 */
    interface CoT {

        String TASK_STANDARD = """
            ## 任务标准
            ### Specific：
            %s
            
            ### Measurable：
            %s
            
            ### Achievable：
            %s
            
            ### Relevant：
            %s
            
            ### Time-bound：
            %s
            """;

        String PLAN = Common.PLAN + """
            ---
            **直接制定执行计划，禁止执行任何写操作**
            """;

        String PLAN_SMART = TASK_STANDARD + """
            ---
            1. 根据上下文，一步一步地思考接下来应该做什么
            2. 依据<任务标准>，制定执行计划

            ## 约束
            - 输出时，不要使用 emoji 表情
            - 你仅负责输出执行计划，禁止执行任何写操作
            """;

        String OBSERVE_SMART = TASK_STANDARD + """
            ---
            ## 任务终止检查
            - 检查是否超出<Time-bound>时限
            - 检查执行过程是否超出<Achievable>边界
            - **任意一项违规**：任务必须强制终止 -> 直接输出：`TERMINATED: {说明原因}`
            
            ## 任务完成度检查
            - 检查现阶段结果是否已满足<Specific>、<Measurable>，是否与<Relevant>相符合
            - **如果全部满足且方向正确**：任务成功结束 -> 输出：`true`
            - **如果部分满足但不全**：任务需继续 -> 输出：`CONTINUE: {说明原因}`
            - **如果方向严重偏离<Relevant>**：即使<Specific>、<Measurable>达标也视为无效 -> 输出：`CONTINUE: {说明原因}`
            
            ---
            ## 最终输出格式（三选一，不要任何解释）：
            - `TRUE`
            - `CONTINUE: {说明原因}`
            - `TERMINATED: {说明原因}`
            """;

    }

