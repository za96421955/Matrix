package com.matrix.service.service.agent;

/**
 * 智能体深度模式提示词
 * <p> <功能详细描述> </p>
 *
 * @author 陈晨
 */
public interface PromptDeep {

    /** 钩子: 人类在环 */
    interface Hook {

        String TODO = """
            ---
            ## 信息补充
            - 发现任何问题或疑问，立即向用户提出
            """;

    }

    /** 检查 */
    interface Check {

        String GOAL = """
            检查<任务目标>是否有疑问或需要用户补充的信息
            - 通过: PASS; 有疑问: TODO
            - 仅输出 PASS/TODO, 不要任何解释
            """;

        String FENCE = """
            检查<安全便捷>是否有疑问或需要用户补充的信息
            - 通过: PASS; 有疑问: TODO
            - 仅输出 PASS/TODO, 不要任何解释
            """;

        String INFO = """
            检查<信息收集方案>是否有疑问或需要用户补充的信息
            - 通过: PASS; 有疑问: TODO
            - 仅输出 PASS/TODO, 不要任何解释
            """;

        String PLAN = """
            检查<执行计划>是否有疑问或需要用户补充的信息
            - 通过: PASS; 有疑问: TODO
            - 仅输出 PASS/TODO, 不要任何解释
            """;

        String RESULT = """
            检查<执行结果>是否有疑问或需要用户补充的信息
            - 通过: PASS; 需要暂停: TODO
            - 仅输出 PASS/TODO, 不要任何解释
            """;

        String OUTPUT_FORMAT = """
            格式错误: %s
            ---
            按<输出格式> (JSON Schema) 要求生成 JSON Object
            """;

    }

    /** 目标 */
    interface Goal {

        String DEVELOP = """
            查看上下文，制定任务目标
            - 确定核心目标，清晰界定'要完成什么'
            - 明确验收标准，包含数字/比率/交付物等量化指标
            - 明确任务方向、意图

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            """;

        String DEVELOP_HOOK = DEVELOP + Hook.TODO;

    }

    /** 安全 */
    interface Fence {

        String CHECK = """
            ---
            ## 终止规则：
            违反以上任何原则，则立即输出"TERMINATE"标记，终止任务

            ## 约束
            - 输出时，不要使用 emoji 表情
            - 禁止执行任何写操作
            
            ## 输出格式（二选一，不要任何解释或说明）：
            - `PASS`
            - `TERMINATE: {终止原因}`
            """;

        String PRIMARY = """
            查看上下文，检查用户任务是否违规：
            - 宪法根本原则审查：凡任务内容涉及反对宪法确立的社会主义制度、危害国家安全、破坏国家统一、煽动民族分裂或颠覆国家政权的，一律判定为违规，直接拒绝。
            - 违法信息红线审查：凡任务内容含有法律明令禁止的违法信息（包括但不限于侮辱诽谤他人、侵害英雄烈士名誉荣誉、散布谣言扰乱秩序、宣扬恐怖主义或极端主义、传播淫秽色情暴力及教唆犯罪等），一律判定为违规，不予通过。
            - 道德与公序良俗审查：凡任务内容存在低俗庸俗媚俗、地域或人群歧视、不当评述灾难事件、诱导未成年人不良行为、煽动不良价值观或违背社会公德等不良导向的，不予通过，须退回整改或标记风险。
            """ + CHECK;

        String DEVELOP = """
            查看上下文，制定任务安全边界
            - 确定最核心的3条安全红线
            - 一步一步地仔细考虑清楚，安全边界一旦触发、任务将会立即停止

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            
            ## 输出格式 (JSON Schema)，生成 JSON Object
            ```json
            %s
            ```
            """;

        String DEVELOP_HOOK = DEVELOP + Hook.TODO;

    }

    /** 信息 */
    interface Information {

        String DEVELOP = """
            查看上下文，制定信息收集方案
            - 信息来源必须为本地或互联网公开信息
            - 数据源必须真实可核查、证据链充分、立场保持客观中立
            - 最多制定3个没有前后关系、可同时进行的执行步骤

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            
            ## 输出格式 (JSON Schema)，生成 JSON Object
            ```json
            %s
            ```
            """;

        String DEVELOP_HOOK = DEVELOP + Hook.TODO;

        String EXECUTE = """
            你是整个执行计划的一环
            - 按执行方案收集信息
            - 来自互联网的网页信息，清洗无效的样式信息后后再查看
            - 详细总结执行过程及结果

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 你仅负责收集信息，不执行任何信息收集任务以外的其他任务
            
            ## 执行方案
            ```
            %s
            ```
            """;

        String REVIEW = """
            查看上下文，对收集的信息进行事实核查
            - 数据源真实、来源清晰
            - 不允许存在任何凭空捏造的数据
            - 信息内容立场保持客观中立
            """;

    }

    /** 计划 */
    interface Plan {

        String FORWARD_LOOKING = """
            查看上下文，根据任务目标和已收集的数据（数据来源包括本地系统和互联网公开渠道），进行一次开放式的前瞻性决策和探索
            - 数据概览：快速描述数据的基本特征
            - 异常与趋势识别：自动检测数据中的异常波动、突增/突降点、关联性变化、舆情热点等，并指出可能隐含的前兆信号
            - 多维度前瞻假设：基于上述信号，从至少3个不同角度分别提出你认为值得关注的方向和假设，每个假设要简要说明“依据是什么”和“为什么值得关注”
            - 缺失与建议：指出当前数据可能不足以支撑哪些方向的深入分析，并建议额外补充哪些数据或信息
            
            ## 输出要求
            - 用要点+简短解释的方式，不求深入建模，但求覆盖面上广、启发性强
            - 最终输出一份“探索性参考简报”，为下一步制定执行计划提供参考
            
            ## 约束
            - 输出时，不要使用 emoji 表情
            - 禁止执行任何写操作
            """;

        String DEVELOP = """
            查看上下文，参考<前瞻决策>建议，制定任务执行计划
            - 围绕任务目标，一步一步地确定任务执行步骤
            - 数据源必须为前置步骤已收集完成的真实信息
            
            ## 约束
            - 输出时，不要使用 emoji 表情
            - 禁止执行任何写操作
            
            ## 任务列表格式
            ```markdown
            ## 任务列表
            - [ ] {待执行的任务描述}
            
            ## 约束
            - {执行操作时的约束条件}
            ```
            """;

        String DEVELOP_HOOK = DEVELOP + Hook.TODO;

    }

    /** 执行 */
    interface Action {

        String SINGLE_RUN = """
            查看执行计划，判断是否一次执行即可完成任务、或需要拆分为至多3个步骤执行
            - 采用最简执行逻辑进行判断，不随意膨胀操作步骤

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            
            ## 执行计划
            ```
            %s
            ```
            
            ## 输出格式（二选一，不要任何解释或说明）：
            - `SINGLE`
            - `MULTI`
            """;

        String DEVELOP = """
            查看上下文，生成执行方案
            - 围绕任务目标和<当前执行计划>，输出执行方案
            - 最多制定3个执行步骤

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            
            ## 当前执行计划
            ```
            %s
            ```
            
            ## 输出格式 (JSON Schema)，生成 JSON Object
            ```json
            %s
            ```
            """;

        String EXECUTE = """
            你是整个执行计划的一环
            - 调用工具，按执行方案，完成当前步骤任务
            - 详细总结执行过程及结果，不要使用任何 emoji 表情
            
            ## 执行方案
            ```
            %s
            ```
            """;

        String EXECUTE_HOOK = EXECUTE + Hook.TODO;

        String REVIEW = """
            查看上下文，对执行结果进行事实核查
            - 执行过程和结果未偏离任务目标
            - 执行过程和结果未偏离执行方案
            - 执行过程和结果立场保持客观中立
            - 不存在任何凭空捏造的数据

            ## 约束
            - 输出时，不要使用任何 emoji 表情
            - 禁止执行任何写操作
            
            ## 输出格式（二选一，不要任何解释或说明）：
            - `PASS`
            - `REVISE: {修订说明}`
            """;

    }

}


